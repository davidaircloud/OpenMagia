// Run against an isolated UI fixture, never a user's active project.
const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const BASE=process.env.OPENMAGIA_TEST_URL||'http://127.0.0.1:8732';
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1050}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const activate=await page.request.post(BASE+'/api/models/select',{data:{kind:'h3_backend',model_id:'fastvideo',role:'video_generation'}});assert.equal(activate.ok(),true);
 await page.goto(BASE);await page.waitForTimeout(800);
 await page.evaluate(()=>setHubView('editor'));
 await page.locator('[data-inspector-tab=generate]').click();
 await page.locator('#genType').selectOption('video');
 await page.locator('#modelCapabilityNotice').waitFor({state:'visible'});
 assert.match(await page.locator('#modelCapabilityNotice').innerText(),/FastVideo needs at least 5 seconds/);
 const links=page.locator('#modelCapabilityNotice .actionLink');
 assert.equal(await links.count(),2);
 const treatment=async locator=>locator.evaluate(el=>{const s=getComputedStyle(el);return [s.color,s.backgroundColor,s.borderColor,s.padding,s.font,s.textDecorationLine]});
 assert.deepEqual(await treatment(links.nth(0)),await treatment(links.nth(1)));
 await links.nth(0).hover();const firstHover=await treatment(links.nth(0));
 await links.nth(1).hover();assert.deepEqual(firstHover,await treatment(links.nth(1)));
 await page.mouse.move(0,0);
 for(const width of [280,330,400]){
  await page.evaluate(w=>document.querySelector('main').style.gridTemplateColumns='250px minmax(200px,1fr) '+w+'px',width);
  const layout=await page.locator('.composerBar').first().evaluate(el=>[...el.querySelectorAll('button')].filter(b=>!b.hidden).every(b=>{const r=b.getBoundingClientRect(),p=el.getBoundingClientRect();return b.scrollHeight<=b.clientHeight+1&&b.scrollWidth<=b.clientWidth+1&&r.right<=p.right+1}));
  assert.equal(layout,true,'Toolbar fits at '+width);
 }
 await page.evaluate(()=>document.querySelector('main').style.gridTemplateColumns='');
 const chevronCentered=await page.locator('#sharedStyleExpand').evaluate(el=>{const a=el.getBoundingClientRect(),b=el.querySelector('svg').getBoundingClientRect();return Math.abs((a.top+a.bottom-b.top-b.bottom)/2)<1});
 assert.equal(chevronCentered,true);
 assert.equal(await page.locator('#videoGenerationControls').evaluate(el=>getComputedStyle(el).borderRadius),'13px');
 assert.equal(await page.locator('#genSteps').isVisible(),false);
 assert.match(await page.locator('#modelPickerBtn').innerText(),/FastVideo/);
 await page.getByRole('button',{name:'Use 5 seconds',exact:true}).click();
 assert.equal(await page.locator('#genFrames').inputValue(),'120');
 assert.equal(await page.locator('#modelCapabilityNotice').isVisible(),false);
 await page.evaluate(()=>{sourceSelection={mediaId:'test',frame:'last',name:'Test clip'};renderSourceContext();});
 assert.match(await page.locator('#modelCapabilityNotice').innerText(),/FastVideo can’t use an opening frame/);
 await page.screenshot({path:'/tmp/openmagia-fastvideo-capability.png'});
 await page.getByRole('button',{name:'Switch to H3',exact:true}).click();
 await page.waitForFunction(()=>engine.h3_backend==='h3-metal');
 assert.equal(await page.locator('#modelCapabilityNotice').isVisible(),false);
 assert.equal(await page.locator('#genSteps').isVisible(),true);
 await page.locator('#modelPickerBtn').click();
 await page.locator('#composerPickerList .pickerRow').filter({hasText:'H3MLX'}).click();
 await page.locator('#pickerApply').click();
 await page.waitForFunction(()=>engine.h3_backend==='h3mlx');
 assert.match(await page.locator('#modelPickerBtn').innerText(),/H3MLX/);
 await page.locator('#genType').selectOption('image');
 assert.equal(await page.locator('#imageModel').isVisible(),true);
 assert.equal(await page.locator('#modelPickerBtn').isVisible(),false);
 await page.locator('#imageModel').selectOption('qwen-image');
 await page.locator('#sharedStyleExpand').click();
 assert.equal(await page.locator('#sharedStyleBody').isVisible(),true);
 await page.locator('#genStyle').fill('Warm natural light');
 await page.locator('#sharedStyleEnabled').check();
 await page.locator('#sharedStyleEnabled').uncheck();
 await page.locator('#sharedStyleExpand').click();
 assert.equal(await page.locator('#sharedStyleBody').isVisible(),false);
 assert.equal(await page.locator('#genStyle').inputValue(),'Warm natural light');
 await page.screenshot({path:'/tmp/openmagia-image-composer.png'});
 await page.locator('#genType').selectOption('storyboard');
 assert.equal(await page.locator('#genBtn').isVisible(),false);
 await page.locator('#openStoryboardBtn').click();
 assert.equal(await page.locator('#storyboardStyleBody').isVisible(),false);
 await page.locator('#storyboardStyleExpand').click();
 assert.equal(await page.locator('#storyboardStyleBody').isVisible(),true);
 await page.screenshot({path:'/tmp/openmagia-storyboard-style.png'});
 await page.locator('#storyboardClose').click();
 await page.evaluate(()=>setHubView('settings'));
 await page.getByRole('button',{name:'Available',exact:true}).click();
 assert.match(await page.locator('#settingsBody').innerText(),/FastVideo/);
 await page.screenshot({path:'/tmp/openmagia-fastvideo-settings.png'});
 assert.deepEqual(errors,[]);
 await browser.close();console.log('FastVideo capability messages, model switch and Settings passed.');
})().catch(e=>{console.error(e);process.exit(1);});
